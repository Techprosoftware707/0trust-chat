package io.lumen.secure.security

import android.content.Context
import android.content.pm.PackageManager
import android.os.Build
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.security.keystore.StrongBoxUnavailableException
import io.lumen.secure.core.security.KeyWrapper
import io.lumen.secure.core.security.SealedBlob
import io.lumen.secure.log.LumenLog
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * AES-256-GCM key in the Android Keystore (ADR 0003 D7):
 * - non-exportable; StrongBox-backed when the device has StrongBox, TEE otherwise;
 * - no user-authentication binding and no unlocked-device requirement, because push
 *   notifications are decrypted in the background while the screen is locked;
 * - IVs are generated by the Keystore (randomised encryption required).
 */
class KeystoreKeyWrapper(private val context: Context, private val alias: String) : KeyWrapper {

    private val keyStore: KeyStore by lazy { KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) } }

    /** True when the current key lives in StrongBox (reported in the Security screen). */
    @Volatile
    var strongBoxBacked: Boolean? = null
        private set

    @Synchronized
    private fun key(): SecretKey {
        (keyStore.getKey(alias, null) as? SecretKey)?.let { return it }
        val wantStrongBox = Build.VERSION.SDK_INT >= Build.VERSION_CODES.P &&
            context.packageManager.hasSystemFeature(PackageManager.FEATURE_STRONGBOX_KEYSTORE)
        if (wantStrongBox) {
            try {
                return generate(strongBox = true).also { strongBoxBacked = true }
            } catch (e: StrongBoxUnavailableException) {
                LumenLog.w("keystore", "StrongBox unavailable, using TEE", e)
            }
        }
        return generate(strongBox = false).also { strongBoxBacked = false }
    }

    private fun generate(strongBox: Boolean): SecretKey {
        val spec = KeyGenParameterSpec.Builder(alias, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setRandomizedEncryptionRequired(true)
            .setUserAuthenticationRequired(false)
            .apply { if (strongBox && Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) setIsStrongBoxBacked(true) }
            .build()
        return KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE).run {
            init(spec)
            generateKey()
        }
    }

    override fun seal(plaintext: ByteArray, associatedData: ByteArray): SealedBlob {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key())
        cipher.updateAAD(associatedData)
        val ct = cipher.doFinal(plaintext)
        return SealedBlob(cipher.iv, ct)
    }

    override fun open(blob: SealedBlob, associatedData: ByteArray): ByteArray {
        val key = keyStore.getKey(alias, null) as? SecretKey ?: throw IllegalStateException("key missing")
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(128, blob.iv))
        cipher.updateAAD(associatedData)
        return cipher.doFinal(blob.ciphertext)
    }

    @Synchronized
    override fun deleteKey() {
        if (keyStore.containsAlias(alias)) keyStore.deleteEntry(alias)
        strongBoxBacked = null
    }

    private companion object {
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
    }
}
