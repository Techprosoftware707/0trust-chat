#!/usr/bin/env bash
# Android app against a real Lumen server, on an emulator. Run on the server host (the CI runner)
# once the emulator is up (adb sees one device) and the server answers with its test CA:
#
#   LUMEN_E2E_SERVER=10-1-0-4.sslip.io LUMEN_E2E_CA=ca.crt LUMEN_E2E_OUT=out \
#   LUMEN_E2E_APK=app-x86_64-debug.apk LUMEN_E2E_TEST_APK=app-debug-androidTest.apk \
#     bash tests/apps/android-e2e/run.sh
#
#  1. the device trusts the server's test CA as a user CA (device-ca.sh, as Settings does);
#  2. the debug app and its instrumentation are installed;
#  3. a portal account is created for the Android user (web-user.mjs account);
#  4. phase a (instrumented): discovery, SSO sign-in, sync, keys on the server;
#  5. a web user (Playwright) opens an encrypted DM with the Android user and writes;
#     phase b (instrumented): accept, read decrypted, reply; the web user sees the reply
#     decrypted; the database holds only ciphertext for the room;
#  6. phase c (instrumented): sign-out; the token is refused; the server has no device left.
#
# Prints PASS/FAIL lines (also in $LUMEN_E2E_OUT/summary.txt); exit status 0 only if all passed.
# The Android user's password is generated by web-user.mjs, masked in GitHub logs and passed to
# the instrumentation only; tokens never leave the app process.
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SERVER="${LUMEN_E2E_SERVER:?}"
CA="${LUMEN_E2E_CA:?}"
OUT="${LUMEN_E2E_OUT:?}"
APK="${LUMEN_E2E_APK:?}"
TEST_APK="${LUMEN_E2E_TEST_APK:?}"
LUMENCTL="${LUMENCTL:-/opt/lumen/lumenctl}"
export LUMENCTL
PKG=io.lumen.secure
RUNNER="$PKG.test/androidx.test.runner.AndroidJUnitRunner"
CLASS=io.lumen.secure.e2e.ServerE2eTest

mkdir -p "$OUT"/instrumentation "$OUT"/screenshots "$OUT"/web
SUMMARY="$OUT/summary.txt"
: >"$SUMMARY"
STATE="$(mktemp -d)"
chmod 700 "$STATE"
FAILED=0
A_PW=""
LOGCAT_PID=""
PEER_PID=""

say() { printf '%s\n' "$*" | tee -a "$SUMMARY"; }
pass() { say "PASS $*"; }
fail() { say "FAIL $*"; FAILED=1; }
section() { printf '\n==> %s\n' "$*" | tee -a "$SUMMARY"; }

sql() {
  local cmd=("$LUMENCTL" compose exec -T postgres psql -qAtU postgres -d synapse -c "$1")
  if [[ $EUID -eq 0 ]]; then "${cmd[@]}"; else sudo -n "${cmd[@]}"; fi
}

# shellcheck disable=SC2317  # invoked through the EXIT trap
finish() {
  [[ -n "$PEER_PID" ]] && kill "$PEER_PID" 2>/dev/null
  adb pull "/sdcard/Android/data/$PKG/files/e2e" "$OUT/screenshots/in-test" >/dev/null 2>&1 || true
  [[ -n "$LOGCAT_PID" ]] && kill "$LOGCAT_PID" 2>/dev/null
  # Secret check on everything that becomes an artifact: the only secret held here is A's password.
  if [[ -n "$A_PW" ]] && grep -rlF -- "$A_PW" "$OUT" >/dev/null 2>&1; then
    grep -rlF -- "$A_PW" "$OUT" | while read -r f; do sed -i "s/$A_PW/[redacted]/g" "$f"; done
    fail "the test password appeared in an output file (redacted before upload)"
  fi
  rm -rf "$STATE"
  printf '\n'
  if ((FAILED)); then say "android e2e: FAILED"; else say "android e2e: all steps passed"; fi
}
trap finish EXIT

# Lines the instrumented test logged (STEP/PASS/FAIL) since the given logcat line count.
test_lines() { tail -n +"$(($1 + 1))" "$OUT/logcat.txt" | grep -E ' LumenE2E: (STEP|PASS|FAIL|signed in|server view|redirect chain)' | sed -E 's/^.* LumenE2E: /    [device] /' || true; }

run_phase() { # run_phase <method> [-e KEY VALUE]...
  local method="$1"; shift
  local raw="$OUT/instrumentation/$method.txt" mark
  mark="$(wc -l <"$OUT/logcat.txt")"
  adb shell am instrument -w -r -e class "$CLASS#$method" -e LUMEN_E2E_SERVER "$SERVER" "$@" "$RUNNER" >"$raw" 2>&1
  sleep 2
  test_lines "$mark" | tee -a "$SUMMARY"
  if python3 "$HERE/instrumentation.py" "$raw" --junit "$OUT/instrumentation/$method.xml" | tee -a "$SUMMARY"; then
    return 0
  fi
  adb exec-out screencap -p >"$OUT/screenshots/$method-after.png" 2>/dev/null || true
  FAILED=1
  return 1
}

adb wait-for-device
: >"$OUT/logcat.txt"

section "Device trusts the server's test CA as a user CA"
if bash "$HERE/device-ca.sh" "$CA" 2>&1 | tee "$OUT/device-ca.txt"; then
  pass "test CA installed in the device's user CA store (as Settings > Install a certificate does)"
else
  fail "could not install the test CA as a user CA"; exit 1
fi
CA_SHA256="$(openssl x509 -in "$CA" -noout -fingerprint -sha256 | cut -d= -f2)"

# After device-ca.sh: `adb root` restarts adbd, which would end a logcat started earlier.
adb logcat -c || true
adb logcat -v threadtime >"$OUT/logcat.txt" 2>&1 &
LOGCAT_PID=$!

section "Install the debug app and its instrumentation"
if adb install -r "$APK" >"$OUT/install-apk.txt" 2>&1 && adb install -r -t "$TEST_APK" >>"$OUT/install-apk.txt" 2>&1; then
  pass "installed $(basename "$APK") and $(basename "$TEST_APK")"
else
  fail "adb install failed: $(tail -n 3 "$OUT/install-apk.txt")"; exit 1
fi

section "Portal account for the Android user"
if node "$HERE/web-user.mjs" account --base "$SERVER" --file "$STATE/a.json" --out "$OUT/web" >"$OUT/web/account.log" 2>&1; then
  A_USER="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["username"])' "$STATE/a.json")"
  A_PW="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["password"])' "$STATE/a.json")"
  [[ -n "${GITHUB_ACTIONS:-}" ]] && echo "::add-mask::$A_PW"
  A_ID="@$A_USER:$SERVER"
  grep -E '^(PASS|FAIL)' "$OUT/web/account.log" | sed 's/^/    [web] /' | tee -a "$SUMMARY"
  pass "portal account $A_ID created (password generated at runtime, not printed)"
else
  cat "$OUT/web/account.log"; fail "portal sign-up for the Android user failed"; exit 1
fi

section "Phase a: discovery and single sign-on in the app"
if run_phase a_signInThroughPortalSso -e LUMEN_E2E_USER "$A_USER" -e LUMEN_E2E_PASSWORD "$A_PW" -e LUMEN_E2E_CA_SHA256 "$CA_SHA256"; then
  pass "phase a: the app signed in through the portal's SSO and synced"
  name="$(sql "SELECT display_name FROM devices WHERE user_id = '$A_ID' AND display_name LIKE 'Lumen on %' LIMIT 1" 2>/dev/null)"
  keys="$(sql "SELECT count(*) FROM e2e_device_keys_json WHERE user_id = '$A_ID'" 2>/dev/null)"
  if [[ -n "$name" && "${keys:-0}" -ge 1 ]]; then
    pass "server database: device '$name' with published device keys"
  else
    fail "server database: expected a named device with keys for $A_ID (name='$name', keys='$keys')"
  fi
else
  fail "phase a (sign-in) failed"; exit 1
fi

section "Phase b: encrypted direct chat with a web user"
MARK_WEB="web-$(openssl rand -hex 8)"
MARK_APP="android-$(openssl rand -hex 8)"
node "$HERE/web-user.mjs" peer --base "$SERVER" --peer "$A_ID" --send "$MARK_WEB" --expect "$MARK_APP" \
  --state "$STATE" --out "$OUT/web" >"$OUT/web/peer.log" 2>&1 &
PEER_PID=$!
for _ in $(seq 1 600); do
  [[ -f "$STATE/sent.json" ]] && break
  kill -0 "$PEER_PID" 2>/dev/null || break
  sleep 1
done
if [[ ! -f "$STATE/sent.json" ]]; then
  grep -E '^(PASS|FAIL| {5})' "$OUT/web/peer.log" | sed 's/^/    [web] /' | tee -a "$SUMMARY"
  fail "the web user did not get to send a message"; exit 1
fi
B_ID="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["userId"])' "$STATE/sent.json")"
pass "web user $B_ID invited the Android user to an encrypted DM and wrote in it"
if run_phase b_encryptedChatWithWebUser -e LUMEN_E2E_EXPECT "$MARK_WEB" -e LUMEN_E2E_REPLY "$MARK_APP" -e LUMEN_E2E_PEER "$B_ID"; then
  pass "phase b: the app accepted, decrypted the web user's message and replied"
else
  fail "phase b (encrypted chat) failed"
  kill "$PEER_PID" 2>/dev/null
fi
wait "$PEER_PID"; peer_rc=$?
PEER_PID=""
grep -E '^(PASS|FAIL| {5})' "$OUT/web/peer.log" | sed 's/^/    [web] /' | tee -a "$SUMMARY"
if ((peer_rc == 0)); then
  pass "web user: reply from Android decrypted; database holds only ciphertext for the room"
else
  fail "web user side failed (see web/peer.log)"; exit 1
fi

section "Phase c: sign-out"
if run_phase c_signOutEndsTheSession -e LUMEN_E2E_SIGN_OUT true; then
  pass "phase c: sign-out invalidated the token and deleted the local data"
  devices="$(sql "SELECT count(*) FROM devices WHERE user_id = '$A_ID'" 2>/dev/null)"
  tokens="$(sql "SELECT count(*) FROM access_tokens WHERE user_id = '$A_ID'" 2>/dev/null)"
  if [[ "$devices" == 0 && "$tokens" == 0 ]]; then
    pass "server database: no device and no access token left for $A_ID"
  else
    fail "server database: $A_ID still has devices=$devices access_tokens=$tokens"
  fi
else
  fail "phase c (sign-out) failed"
fi
exit "$FAILED"
