#!/usr/bin/env python3
"""Generate native design tokens from design/tokens.css (the single source).

    python3 design/tools/gen_tokens.py            # write the generated files
    python3 design/tools/gen_tokens.py --check    # exit 1 if they are out of date (CI)

Outputs:
    apps/android/app/src/main/java/io/lumen/secure/ui/theme/LumenTokens.kt
    apps/ios/Lumen/DesignSystem/LumenTokens.swift

Only plain values are exported: colours (hex or rgba, after resolving var()
references), lengths in rem/px (as density-independent points: 1rem = 16),
durations in ms. Gradients, shadows and clamp() are platform-specific and are
re-expressed by hand in each app's theme code.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "design" / "tokens.css"
OUT_KT = REPO / "apps/android/app/src/main/java/io/lumen/secure/ui/theme/LumenTokens.kt"
OUT_SWIFT = REPO / "apps/ios/Lumen/DesignSystem/LumenTokens.swift"

DECL = re.compile(r"--([a-z0-9-]+)\s*:\s*([^;]+);")
HEX = re.compile(r"^#([0-9a-fA-F]{6})$")
RGBA = re.compile(r"^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([0-9.]+)\s*\)$")
LEN = re.compile(r"^([0-9.]+)(rem|px)$")
MS = re.compile(r"^([0-9.]+)ms$")


def blocks(css: str) -> tuple[dict[str, str], dict[str, str]]:
    """Returns (light/root declarations, dark declarations)."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    root: dict[str, str] = {}
    dark: dict[str, str] = {}
    # :root { ... } blocks (the first ones hold palette, scale and light theme)
    for m in re.finditer(r":root\s*\{(.*?)\n\}", css, flags=re.S):
        root.update({k: v.strip() for k, v in DECL.findall(m.group(1))})
    m = re.search(r':root\[data-theme="dark"\]\s*\{(.*?)\n\}', css, flags=re.S)
    if not m:
        raise SystemExit("tokens.css: dark theme block not found")
    dark.update({k: v.strip() for k, v in DECL.findall(m.group(1))})
    return root, dark


def resolve(value: str, scope: dict[str, str], depth: int = 0) -> str:
    if depth > 10:
        raise SystemExit(f"tokens.css: var() cycle at {value}")
    m = re.fullmatch(r"var\(--([a-z0-9-]+)\)", value)
    if m:
        return resolve(scope[m.group(1)], scope, depth + 1)
    return value


def color(value: str) -> tuple[int, int, int, float] | None:
    if m := HEX.match(value):
        h = m.group(1)
        return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 1.0
    if m := RGBA.match(value):
        return int(m.group(1)), int(m.group(2)), int(m.group(3)), float(m.group(4))
    return None


def camel(name: str) -> str:
    parts = name.split("-")
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return re.sub(r"^(\d)", r"n\1", out)


THEME_KEYS = [
    "bg", "bg-elevated", "surface", "surface-2", "surface-3", "surface-inverse", "border", "border-strong",
    "text", "text-muted", "text-subtle", "text-inverse", "accent", "accent-hover", "accent-soft",
    "accent-contrast", "accent-2", "accent-3", "success", "success-soft", "warning", "warning-soft",
    "danger", "danger-soft", "info", "info-soft", "bubble-own", "bubble-other",
]


def collect() -> dict:
    root, dark = blocks(SRC.read_text())
    palette = {k: color(v) for k, v in root.items() if k.startswith("lm-") and color(v)}
    light_scope = dict(root)
    dark_scope = {**root, **dark}
    themes = {}
    for name, scope in (("light", light_scope), ("dark", dark_scope)):
        t = {}
        for k in THEME_KEYS:
            c = color(resolve(scope[k], scope))
            if c is None:
                raise SystemExit(f"tokens.css: --{k} ({name}) is not a plain colour")
            t[k] = c
        themes[name] = t
    dims = {}
    for k, v in root.items():
        if k.startswith(("space-", "radius-", "text-")) and (m := LEN.match(v)):
            n = float(m.group(1)) * (16 if m.group(2) == "rem" else 1)
            dims[k] = n
    durations = {k: float(MS.match(v).group(1)) for k, v in root.items() if MS.match(v)}
    return {"palette": palette, "themes": themes, "dims": dims, "durations": durations}


HEADER = "Generated by design/tools/gen_tokens.py from design/tokens.css. Do not edit."


def argb(c) -> str:
    r, g, b, a = c
    return f"0x{round(a * 255):02X}{r:02X}{g:02X}{b:02X}"


def num(n: float) -> str:
    return f"{n:g}"


def kotlin(t: dict) -> str:
    L = [f"// {HEADER}", "package io.lumen.secure.ui.theme", "",
         "import androidx.compose.ui.graphics.Color", "import androidx.compose.ui.unit.dp", "import androidx.compose.ui.unit.sp", "",
         "object LumenPalette {"]
    L += [f"    val {camel(k[3:])} = Color({argb(c)})" for k, c in sorted(t["palette"].items())]
    L += ["}", "", "data class LumenColors("]
    L += [f"    val {camel(k)}: Color," for k in THEME_KEYS]
    L += [")", ""]
    for name, theme in t["themes"].items():
        L.append(f"val Lumen{name.capitalize()}Colors = LumenColors(")
        L += [f"    {camel(k)} = Color({argb(theme[k])})," for k in THEME_KEYS]
        L += [")", ""]
    L.append("object LumenDimens {")
    for k, n in sorted(t["dims"].items()):
        unit = "sp" if k.startswith("text-") else "dp"
        L.append(f"    val {camel(k)} = {num(n)}.{unit}")
    L += ["}", "", "object LumenMotion {"]
    L += [f"    const val {camel(k)}Millis = {int(n)}" for k, n in sorted(t["durations"].items())]
    L += ["}", ""]
    return "\n".join(L)


def swift(t: dict) -> str:
    def col(c):
        r, g, b, a = c
        return f"Color(.sRGB, red: {r / 255:.4f}, green: {g / 255:.4f}, blue: {b / 255:.4f}, opacity: {a:g})"
    L = [f"// {HEADER}", "import SwiftUI", "", "enum LumenPalette {"]
    L += [f"    static let {camel(k[3:])} = {col(c)}" for k, c in sorted(t["palette"].items())]
    L += ["}", "", "struct LumenColors {"]
    L += [f"    let {camel(k)}: Color" for k in THEME_KEYS]
    L += [""]
    for name, theme in t["themes"].items():
        L.append(f"    static let {name} = LumenColors(")
        L += [f"        {camel(k)}: {col(theme[k])}{',' if i < len(THEME_KEYS) - 1 else ''}" for i, k in enumerate(THEME_KEYS)]
        L.append("    )")
    L += ["}", "", "enum LumenDimens {"]
    L += [f"    static let {camel(k)}: CGFloat = {num(n)}" for k, n in sorted(t["dims"].items())]
    L += ["}", "", "enum LumenMotion {"]
    L += [f"    static let {camel(k)}: Double = {n / 1000:g}" for k, n in sorted(t["durations"].items())]
    L += ["}", ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    t = collect()
    outputs = {OUT_KT: kotlin(t), OUT_SWIFT: swift(t)}
    stale = []
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(REPO)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("design tokens out of date (run python3 design/tools/gen_tokens.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
