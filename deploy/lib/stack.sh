# --- Secrets -------------------------------------------------------------------

# gen_secret NAME [BYTES] — create a random hex secret file if it doesn't exist.
gen_secret() {
  local name="$1" bytes="${2:-32}" path="$LUMEN_SECRETS_DIR/$1"
  if [[ ! -s "$path" ]]; then
    umask 077
    openssl rand -hex "$bytes" | tr -d '\n' >"$path"
    _log "SECRET generated $name"
  fi
  chown "root:$GID_SECRETS" "$path"
  chmod 0440 "$path"
}

# ensure_optional_secret NAME — empty placeholder so Compose can mount it.
ensure_optional_secret() {
  local path="$LUMEN_SECRETS_DIR/$1"
  [[ -e "$path" ]] || : >"$path"
  chown "root:$GID_SECRETS" "$path"
  chmod 0440 "$path"
}

ensure_secrets() {
  install -d -m 0750 -o root -g "$GID_SECRETS" "$LUMEN_SECRETS_DIR"
  gen_secret django_secret_key 48
  gen_secret postgres_superuser_password 24
  gen_secret postgres_app_password 24
  gen_secret synapse_db_password 24
  gen_secret synapse_macaroon 32
  gen_secret synapse_form_secret 32
  gen_secret synapse_registration_secret 32
  gen_secret synapse_oidc_client_secret 32
  gen_secret internal_api_token 32
  gen_secret ops_gateway_secret 32
  gen_secret lkjwt_as_token 32
  gen_secret lkjwt_hs_token 32
  ensure_optional_secret smtp_password
  ensure_optional_secret stripe_secret_key
  ensure_optional_secret stripe_webhook_secret
  ensure_optional_secret synapse_admin_token
  # OIDC signing key for the portal identity provider.
  if [[ ! -s "$LUMEN_SECRETS_DIR/oidc_private_key.pem" ]]; then
    (umask 077 && openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:3072 -out "$LUMEN_SECRETS_DIR/oidc_private_key.pem" 2>/dev/null)
    _log "SECRET generated oidc_private_key.pem"
  fi
  chown "root:$GID_SECRETS" "$LUMEN_SECRETS_DIR/oidc_private_key.pem"
  chmod 0440 "$LUMEN_SECRETS_DIR/oidc_private_key.pem"
  # libpq requires its passfile to be owned by the reading user and mode 0600.
  local pw
  pw="$(cat "$LUMEN_SECRETS_DIR/synapse_db_password")"
  (umask 077 && printf 'postgres:5432:synapse:synapse:%s\n' "$pw" >"$LUMEN_SECRETS_DIR/synapse_pgpass")
  chown "$UID_SYNAPSE:$UID_SYNAPSE" "$LUMEN_SECRETS_DIR/synapse_pgpass"
  chmod 0600 "$LUMEN_SECRETS_DIR/synapse_pgpass"
  ensure_calls_secrets
}

# LiveKit API key pair ("<key name>: <secret>", the format LiveKit and lk-jwt-service
# read) and the application-service registration that lets Synapse proxy MatrixRTC
# token requests to lk-jwt-service and lets it check room membership.
ensure_calls_secrets() {
  local f="$LUMEN_SECRETS_DIR/livekit_keys"
  if [[ ! -s "$f" ]]; then
    (umask 077 && printf 'LK%s: %s\n' "$(openssl rand -hex 8)" "$(openssl rand -hex 32)" >"$f")
    _log "SECRET generated livekit_keys"
  fi
  chown "root:$GID_SECRETS" "$f"; chmod 0440 "$f"
  local reg="$LUMEN_SECRETS_DIR/lkjwt_registration"
  (umask 077 && cat >"$reg.tmp" <<REG
# Generated by Lumen. Application service registration for lk-jwt-service
# (MatrixRTC authorization service). It receives no events (url: null); Synapse
# proxies /rtc/livekit requests to it and lets it ask whether a user is joined.
id: lumen-lk-jwt-service
as_token: "$(cat "$LUMEN_SECRETS_DIR/lkjwt_as_token")"
hs_token: "$(cat "$LUMEN_SECRETS_DIR/lkjwt_hs_token")"
sender_localpart: _lk_jwt_service
namespaces:
  users:
    - exclusive: false
      regex: ".*"
  aliases: []
  rooms: []
url: null
rate_limited: false
io.element.msc4502.scopes:
  - "urn:matrix:client:io.element.msc4502:rooms:is_joined"
io.element.msc4512.proxy_prefix: "rtc/livekit"
io.element.msc4512.proxy_url: "http://lkjwt:8080"
REG
  )
  mv -f "$reg.tmp" "$reg"
  chown "root:$GID_SECRETS" "$reg"; chmod 0440 "$reg"
}

# rtc_cert_path — Caddy's certificate for the rtc domain (ACME or internal CA), if issued.
rtc_cert_path() {
  local rtc; rtc="$(rtc_domain)"
  find "$(conf_get LUMEN_DATA_DIR /var/lib/lumen)/caddy/data/caddy/certificates" -path "*/$rtc/$rtc.crt" -type f \
    -printf '%T@ %p\n' 2>/dev/null | sort -rn | head -n1 | cut -d' ' -f2-
}

# sync_rtc_cert — copy the rtc certificate for LiveKit's TURN/TLS listener.
# Returns 0 if the copy changed (LiveKit must be re-rendered/restarted), 1 otherwise.
sync_rtc_cert() {
  calls_enabled || return 1
  local crt key dir
  crt="$(rtc_cert_path)"; [[ -n "$crt" ]] || return 1
  key="${crt%.crt}.key"; [[ -f "$key" ]] || return 1
  dir="$(conf_get LUMEN_DATA_DIR /var/lib/lumen)/livekit/tls"
  install -d -m 0750 -o root -g "$UID_LIVEKIT" "$dir"
  if cmp -s "$crt" "$dir/tls.crt" && cmp -s "$key" "$dir/tls.key"; then return 1; fi
  install -m 0440 -o root -g "$UID_LIVEKIT" "$crt" "$dir/tls.crt"
  install -m 0440 -o root -g "$UID_LIVEKIT" "$key" "$dir/tls.key"
  _log "TURN/TLS certificate updated from $crt"
  return 0
}

