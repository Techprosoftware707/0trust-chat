#!/usr/bin/env bash
# shellcheck disable=SC2154,SC1090  # _log_file/colours come from common.sh; env files are generated
# Builds /etc/lumen/lumen.conf interactively, or validates a provided file.

ask() {
  # ask VAR "Question" default [validator-regex] [hint]
  local __var="$1" q="$2" def="${3:-}" re="${4:-}" hint="${5:-}" ans
  while true; do
    if [[ -n "$def" ]]; then
      read -r -p "  $q [$def]: " ans </dev/tty || die "input aborted"
      ans="${ans:-$def}"
    else
      read -r -p "  $q: " ans </dev/tty || die "input aborted"
    fi
    ans="$(printf '%s' "$ans" | tr -d '[:space:]')"
    if [[ -z "$re" || "$ans" =~ $re ]]; then
      printf -v "$__var" '%s' "$ans"
      return
    fi
    printf '    %s\n' "${hint:-invalid value, try again}"
  done
}

ask_secret() {
  # ask_secret FILE "Question" — stored straight into a secret file, never echoed or logged
  local file="$1" q="$2" ans
  read -r -s -p "  $q (input hidden, empty to skip): " ans </dev/tty || die "input aborted"
  printf '\n'
  if [[ -n "$ans" ]]; then
    install -d -m 0750 -o root -g "$GID_SECRETS" "$LUMEN_SECRETS_DIR"
    (umask 077 && printf '%s' "$ans" >"$LUMEN_SECRETS_DIR/$file")
    chown "root:$GID_SECRETS" "$LUMEN_SECRETS_DIR/$file"; chmod 0440 "$LUMEN_SECRETS_DIR/$file"
  fi
}

ask_yn() {
  local __var="$1" q="$2" def="${3:-n}" ans
  read -r -p "  $q [$( [[ $def == y ]] && echo Y/n || echo y/N )]: " ans </dev/tty || die "input aborted"
  ans="${ans:-$def}"
  [[ "${ans,,}" == y* ]] && printf -v "$__var" true || printf -v "$__var" false
}

DOMAIN_RE='^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z][a-z0-9-]{0,61}[a-z0-9]$'
EMAIL_RE='^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
USER_RE='^[a-z0-9][a-z0-9._-]{1,30}[a-z0-9]$'

interactive_configure() {
  local out="$1"
  [[ -t 0 || -e /dev/tty ]] || die "No configuration file and no terminal for questions. Provide one: sudo bash install.sh --config lumen.conf (see lumen.conf.example)."
  printf '\n%sLumen configuration%s — press Enter to accept the [default].\n' "$C_BOLD" "$C_RESET"
  printf '%sDNS: create A/AAAA records for all five hostnames pointing at this server first.%s\n\n' "$C_DIM" "$C_RESET"
  local primary app matrix ops rtc server_name email opuser regmode fedmode allow calls wg tls smtp_host smtp_port smtp_user smtp_from billing backup_dir
  ask primary "Primary domain (website, portal, Matrix IDs)" "" "$DOMAIN_RE" "e.g. example.com (lowercase)"
  ask app "Chat app domain" "app.$primary" "$DOMAIN_RE"
  ask matrix "Homeserver domain" "matrix.$primary" "$DOMAIN_RE"
  ask ops "Operator console domain (private; needs a DNS record for its certificate)" "ops.$primary" "$DOMAIN_RE"
  ask rtc "Calls (SFU and TURN) domain" "rtc.$primary" "$DOMAIN_RE"
  ask server_name "Matrix server name (user IDs look like @alice:<name>)" "$primary" "$DOMAIN_RE"
  ask email "Administrator email (Let's Encrypt + security contact)" "" "$EMAIL_RE" "enter a valid email"
  ask opuser "Initial operator username" "operator-$(printf '%s' "${email%%@*}" | tr -cd 'a-z0-9' | cut -c1-12)" "$USER_RE" "3-32 chars: a-z 0-9 . _ -"
  ask regmode "Registration: open, invite or closed" "open" '^(open|invite|closed)$'
  ask fedmode "Federation: open, allowlist or closed" "open" '^(open|allowlist|closed)$'
  allow=""
  [[ "$fedmode" == allowlist ]] && ask allow "Allowed servers (comma-separated server names)" "" '^[a-z0-9.,:-]+$'
  ask_yn calls "Enable voice/video calls (LiveKit SFU; opens UDP 7882-7889, TCP 7881, UDP 3478)?" y
  ask_yn wg "Enable WireGuard for private operator access to the console (recommended; opens UDP 51820)?" y
  ask tls "TLS: acme (Let's Encrypt, production) or internal (test CA, testing only)" "acme" '^(acme|internal)$'
  ask smtp_host "SMTP server for account emails (empty = no email)" "" '^[a-z0-9.-]*$'
  smtp_port=587; smtp_user=""; smtp_from=""
  if [[ -n "$smtp_host" ]]; then
    ask smtp_port "SMTP port" "587" '^[0-9]+$'
    ask smtp_user "SMTP username" "" '.*'
    ask_secret smtp_password "SMTP password"
    ask smtp_from "From address" "no-reply@$primary" "$EMAIL_RE"
  fi
  ask billing "Payments: none, manual or stripe" "none" '^(none|manual|stripe)$'
  if [[ "$billing" == stripe ]]; then
    ask_secret stripe_secret_key "Stripe secret key (sk_live_... or sk_test_...)"
    ask_secret stripe_webhook_secret "Stripe webhook signing secret (whsec_...)"
  fi
  ask backup_dir "Backup directory" "/var/backups/lumen" '^/[A-Za-z0-9._/-]+$'
  cat >"$out" <<CONF
# Lumen configuration — generated by install.sh on $(date -u +%F).
# Edit and run 'sudo ./update.sh' to apply. Secrets live in /etc/lumen/secrets, never here.
LUMEN_PRIMARY_DOMAIN=$primary
LUMEN_APP_DOMAIN=$app
LUMEN_MATRIX_DOMAIN=$matrix
LUMEN_OPS_DOMAIN=$ops
LUMEN_RTC_DOMAIN=$rtc
MATRIX_SERVER_NAME=$server_name
ADMIN_EMAIL=$email
OPERATOR_USERNAME=$opuser
TLS_MODE=$tls
REGISTRATION_MODE=$regmode
FEDERATION_MODE=$fedmode
FEDERATION_ALLOWLIST=$allow
CALLS_ENABLED=$calls
WIREGUARD_ENABLED=$wg
SMTP_HOST=$smtp_host
SMTP_PORT=$smtp_port
SMTP_USER=$smtp_user
SMTP_FROM=$smtp_from
BILLING_PROVIDER=$billing
BACKUP_DIR=$backup_dir
CONF
  chmod 0640 "$out"
}

IPV4_RE='^((25[0-5]|2[0-4][0-9]|1[0-9][0-9]|[1-9]?[0-9])\.){3}(25[0-5]|2[0-4][0-9]|1[0-9][0-9]|[1-9]?[0-9])$'

# test_configure OUT — "no domain yet" (install.sh --test): a test installation reached by IP.
#  * Default: hostnames under <ip>.sslip.io (public DNS that resolves 203-0-113-5.sslip.io and
#    every name below it to 203.0.113.5) with Lumen's private test CA, which each test device
#    must trust. Let's Encrypt is not used: sslip.io is not on the Public Suffix List, so all of
#    its users share one rate limit.
#  * With a free DNS name the operator created (DuckDNS, deSEC: on the Public Suffix List, and
#    they resolve every name below yours too), certificates come from Let's Encrypt and devices
#    need nothing installed. The server must then be reachable on 80/443 from the internet.
# Unattended (--yes or no terminal): the values below are used without questions.
test_configure() {
  local out="$1" ip="${LUMEN_TEST_IP:-}" host="${LUMEN_TEST_HOST:-}" pub email opuser regmode calls tls private=false
  if [[ -z "$ip" ]]; then
    pub="$(public_ip)"
    # With a public DNS name (Let's Encrypt), devices reach the server at its public address,
    # also behind cloud NAT where that address is on no interface (preflight checks that the
    # name points there). Without one: the public address only if it is on this host, otherwise
    # the LAN address.
    if [[ -n "$host" && -n "$pub" ]]; then
      ip="$pub"
    elif [[ -n "$pub" ]] && ip -4 -o addr show 2>/dev/null | awk '{print $4}' | cut -d/ -f1 | grep -qxF "$pub"; then
      ip="$pub"
    else
      ip="$(lan_ipv4)"
    fi
  fi
  regmode=open; calls=true; opuser=operator
  if ((ASSUME_YES == 0)) && [[ -t 0 ]]; then
    printf '\n%sTest setup — no domain needed.%s Press Enter to accept the [default].\n' "$C_BOLD" "$C_RESET"
    printf '%sFor testing only: moving to your real domain later means a new installation, because\nMatrix user IDs contain the server name.%s\n\n' "$C_DIM" "$C_RESET"
    ask ip "IP address your test devices use to reach this server" "$ip" "$IPV4_RE" "an IPv4 address, e.g. 203.0.113.5"
    ask host "Free DNS name you created for this IP, e.g. mylumen.duckdns.org (empty: $(sslip_name "$ip"))" "$host" "^$|$DOMAIN_RE"
    ask opuser "Initial operator username" "$opuser" "$USER_RE" "3-32 chars: a-z 0-9 . _ -"
    ask regmode "Registration: open, invite or closed" "$regmode" '^(open|invite|closed)$'
    ask_yn calls "Enable voice/video calls (opens UDP 7882-7889, TCP 7881, UDP 3478)?" y
  fi
  [[ "$ip" =~ $IPV4_RE ]] || die "Test setup: could not determine this server's IP address. Run: sudo bash install.sh --test --test-ip <address>"
  is_private_ipv4 "$ip" && private=true
  if [[ -n "$host" ]]; then
    [[ "$host" =~ $DOMAIN_RE ]] || die "Test setup: '$host' is not a valid host name"
    tls=acme
    email="${LUMEN_TEST_EMAIL:-}"
    if ((ASSUME_YES == 0)) && [[ -t 0 ]]; then
      ask email "Your email (Let's Encrypt account and security contact)" "$email" "$EMAIL_RE" "enter a valid email"
    fi
    [[ "$email" =~ $EMAIL_RE ]] || die "Test setup with a DNS name: an email is needed for Let's Encrypt (--test-email you@example.org)"
  else
    host="$(sslip_name "$ip")"
    tls=internal
    email="${LUMEN_TEST_EMAIL:-admin@$host}"
  fi
  cat >"$out" <<CONF
# Lumen TEST configuration (install.sh --test) — generated on $(date -u +%F).
# For testing only. Moving to a real domain later needs a new installation: the Matrix
# server name ($host) is part of every user ID and cannot be changed afterwards.
LUMEN_TEST_SETUP=true
LUMEN_PRIMARY_DOMAIN=$host
ADMIN_EMAIL=$email
OPERATOR_USERNAME=$opuser
TLS_MODE=$tls
REGISTRATION_MODE=$regmode
# Federation needs a permanent name and a publicly trusted certificate.
FEDERATION_MODE=closed
CALLS_ENABLED=$calls
CALLS_PUBLIC_IP=$ip
CALLS_ALLOW_PRIVATE_NODE_IP=$private
# Private operator access to the console (configured by the installer; see the summary).
WIREGUARD_ENABLED=true
BILLING_PROVIDER=none
CONF
  # Networks with TLS inspection: the inspecting proxy's CA for image builds (as in lumen.conf).
  [[ -n "${LUMEN_BUILD_EXTRA_CA:-}" ]] && printf 'LUMEN_BUILD_EXTRA_CA=%s\n' "$LUMEN_BUILD_EXTRA_CA" >>"$out"
  chmod 0640 "$out"
  info "test setup: https://$host ($( [[ $tls == internal ]] && echo "private test CA" || echo "Let's Encrypt"); server IP $ip$( [[ $private == true ]] && echo ", private network"))"
}

validate_conf_file() {
  local file="$1"
  python3 "$LUMEN_REPO_DIR/deploy/lib/render.py" --conf "$file" --secrets "$LUMEN_SECRETS_DIR" \
    --repo "$LUMEN_REPO_DIR" --out /nonexistent --print-config >/dev/null \
    || die "Configuration $file is invalid (details above). Fix it and re-run."
}
