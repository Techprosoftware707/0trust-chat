#!/usr/bin/env bash
# Builds /etc/lumen/lumen.conf interactively, or validates a provided file.

ask() {
  # ask VAR "Question" default [validator-regex] [hint]
  local __var="$1" q="$2" def="${3:-}" re="${4:-}" hint="${5:-}" ans
  while true; do
    if [[ -n "$def" ]]; then
      read -r -p "  $q [$def]: " ans </dev/tty || die "input aborted"
      ans="${ans:-$def}"
    else
      read -r -p "  $q: " ans </dev/tty || die "input aborted"
    fi
    ans="$(printf '%s' "$ans" | tr -d '[:space:]')"
    if [[ -z "$re" || "$ans" =~ $re ]]; then
      printf -v "$__var" '%s' "$ans"
      return
    fi
    printf '    %s\n' "${hint:-invalid value, try again}"
  done
}

ask_secret() {
  # ask_secret FILE "Question" — stored straight into a secret file, never echoed or logged
  local file="$1" q="$2" ans
  read -r -s -p "  $q (input hidden, empty to skip): " ans </dev/tty || die "input aborted"
  printf '\n'
  if [[ -n "$ans" ]]; then
    install -d -m 0750 -o root -g "$GID_SECRETS" "$LUMEN_SECRETS_DIR"
    (umask 077 && printf '%s' "$ans" >"$LUMEN_SECRETS_DIR/$file")
    chown "root:$GID_SECRETS" "$LUMEN_SECRETS_DIR/$file"; chmod 0440 "$LUMEN_SECRETS_DIR/$file"
  fi
}

ask_yn() {
  local __var="$1" q="$2" def="${3:-n}" ans
  read -r -p "  $q [$( [[ $def == y ]] && echo Y/n || echo y/N )]: " ans </dev/tty || die "input aborted"
  ans="${ans:-$def}"
  [[ "${ans,,}" == y* ]] && printf -v "$__var" true || printf -v "$__var" false
}

DOMAIN_RE='^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z][a-z0-9-]{0,61}[a-z0-9]$'
EMAIL_RE='^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
USER_RE='^[a-z0-9][a-z0-9._-]{1,30}[a-z0-9]$'

interactive_configure() {
  local out="$1"
  [[ -t 0 || -e /dev/tty ]] || die "No configuration file and no terminal for questions. Provide one: sudo bash install.sh --config lumen.conf (see lumen.conf.example)."
  printf '\n%sLumen configuration%s — press Enter to accept the [default].\n' "$C_BOLD" "$C_RESET"
  printf '%sDNS: create A/AAAA records for all four hostnames pointing at this server first.%s\n\n' "$C_DIM" "$C_RESET"
  local primary app matrix ops server_name email opuser regmode fedmode allow voip wg tls smtp_host smtp_port smtp_user smtp_from billing backup_dir
  ask primary "Primary domain (website, portal, Matrix IDs)" "" "$DOMAIN_RE" "e.g. example.com (lowercase)"
  ask app "Chat app domain" "app.$primary" "$DOMAIN_RE"
  ask matrix "Homeserver domain" "matrix.$primary" "$DOMAIN_RE"
  ask ops "Operator console domain (private; needs a DNS record for its certificate)" "ops.$primary" "$DOMAIN_RE"
  ask server_name "Matrix server name (user IDs look like @alice:<name>)" "$primary" "$DOMAIN_RE"
  ask email "Administrator email (Let's Encrypt + security contact)" "" "$EMAIL_RE" "enter a valid email"
  ask opuser "Initial operator username" "operator-$(printf '%s' "${email%%@*}" | tr -cd 'a-z0-9' | cut -c1-12)" "$USER_RE" "3-32 chars: a-z 0-9 . _ -"
  ask regmode "Registration: open, invite or closed" "open" '^(open|invite|closed)$'
  ask fedmode "Federation: open, allowlist or closed" "open" '^(open|allowlist|closed)$'
  allow=""
  [[ "$fedmode" == allowlist ]] && ask allow "Allowed servers (comma-separated server names)" "" '^[a-z0-9.,:-]+$'
  ask_yn voip "Enable 1:1 voice/video calls (runs a TURN relay, opens UDP 3478 + 49160-49200)?" n
  ask_yn wg "Enable WireGuard for private operator access (opens UDP 51820)?" n
  ask tls "TLS: acme (Let's Encrypt, production) or internal (test CA, testing only)" "acme" '^(acme|internal)$'
  ask smtp_host "SMTP server for account emails (empty = no email)" "" '^[a-z0-9.-]*$'
  smtp_port=587; smtp_user=""; smtp_from=""
  if [[ -n "$smtp_host" ]]; then
    ask smtp_port "SMTP port" "587" '^[0-9]+$'
    ask smtp_user "SMTP username" "" '.*'
    ask_secret smtp_password "SMTP password"
    ask smtp_from "From address" "no-reply@$primary" "$EMAIL_RE"
  fi
  ask billing "Payments: none, manual or stripe" "none" '^(none|manual|stripe)$'
  if [[ "$billing" == stripe ]]; then
    ask_secret stripe_secret_key "Stripe secret key (sk_live_... or sk_test_...)"
    ask_secret stripe_webhook_secret "Stripe webhook signing secret (whsec_...)"
  fi
  ask backup_dir "Backup directory" "/var/backups/lumen" '^/[A-Za-z0-9._/-]+$'
  cat >"$out" <<CONF
# Lumen configuration — generated by install.sh on $(date -u +%F).
# Edit and run 'sudo ./update.sh' to apply. Secrets live in /etc/lumen/secrets, never here.
LUMEN_PRIMARY_DOMAIN=$primary
LUMEN_APP_DOMAIN=$app
LUMEN_MATRIX_DOMAIN=$matrix
LUMEN_OPS_DOMAIN=$ops
MATRIX_SERVER_NAME=$server_name
ADMIN_EMAIL=$email
OPERATOR_USERNAME=$opuser
TLS_MODE=$tls
REGISTRATION_MODE=$regmode
FEDERATION_MODE=$fedmode
FEDERATION_ALLOWLIST=$allow
VOIP_ENABLED=$voip
WIREGUARD_ENABLED=$wg
SMTP_HOST=$smtp_host
SMTP_PORT=$smtp_port
SMTP_USER=$smtp_user
SMTP_FROM=$smtp_from
BILLING_PROVIDER=$billing
BACKUP_DIR=$backup_dir
CONF
  chmod 0640 "$out"
}

validate_conf_file() {
  local file="$1"
  python3 "$LUMEN_REPO_DIR/deploy/lib/render.py" --conf "$file" --secrets "$LUMEN_SECRETS_DIR" \
    --repo "$LUMEN_REPO_DIR" --out /nonexistent --print-config >/dev/null \
    || die "Configuration $file is invalid (details above). Fix it and re-run."
}
